#!/usr/bin/env python3
"""FROST: the filters of the DSD to PCM converter (hifi/codec_dsd.c), written to hifi/dsd_fir.h.

Stage 1 (bits to 352.8 kHz): a low-pass FIR over the 1-bit stream, 64, 128 or 256 taps for
DSD64, DSD128 and DSD256 (8, 16 or 32 bytes: one table of 256 sums per byte of history on core
B), decimating by 8, 16 or 32. Stage 2 (352.8 kHz to 88.2 kHz): 96 taps, decimating by 4.
Kaiser windows; the attenuation printed is the worst over the bands that alias into 0-24 kHz.
"""
import numpy as np
from scipy.signal import firwin, freqz

def stage1(taps, fs, out):
    # pass to ~30 kHz, stop where the images of 0-44 kHz around out fold back
    h = firwin(taps, 120e3, window=("kaiser", 9.0), fs=fs)
    w, H = freqz(h, worN=1 << 16, fs=fs)
    stop = np.abs(H[w >= out - 44.1e3]).max()
    pb = np.abs(H[w <= 20e3])
    print(f"stage 1, {taps} taps at {fs/1e6:.4f} MHz: passband {20*np.log10(pb.min()):.3f}.."
          f"{20*np.log10(pb.max()):.3f} dB, alias rejection {20*np.log10(stop):.1f} dB")
    return h

def stage2():
    fs = 352800
    h = firwin(96, 30e3, window=("kaiser", 8.0), fs=fs)
    w, H = freqz(h, worN=1 << 16, fs=fs)
    stop = np.abs(H[w >= 88200 - 24e3]).max()
    pb = np.abs(H[w <= 20e3])
    print(f"stage 2, 96 taps: passband {20*np.log10(pb.min()):.3f}..{20*np.log10(pb.max()):.3f} dB, "
          f"rejection above 64.2 kHz {20*np.log10(stop):.1f} dB")
    return h

out = ["/* Generated by tools/mkdsdfir.py: the filters of hifi/codec_dsd.c */", "#ifndef DSD_FIR_H",
       "#define DSD_FIR_H", "#include <stdint.h>", ""]
for name, taps, fs in (("s1_64", 64, 2822400), ("s1_128", 128, 5644800), ("s1_256", 256, 11289600)):
    h = stage1(taps, fs, 352800)
    q = np.round(h / h.sum() * (1 << 24)).astype(int)        # Q24, gain 1 at DC
    out.append(f"static const int32_t {name}[{taps}] = {{")
    out += ["    " + ", ".join(str(v) for v in q[i:i + 8]) + "," for i in range(0, taps, 8)]
    out.append("};")
h = stage2()
q = np.round(h / h.sum() * (1 << 15)).astype(int)            # Q15
out.append("static const int32_t s2[96] = {")
out += ["    " + ", ".join(str(v) for v in q[i:i + 12]) + "," for i in range(0, 96, 12)]
out += ["};", "", "#endif", ""]
open("hifi/dsd_fir.h", "w").write("\n".join(out))
